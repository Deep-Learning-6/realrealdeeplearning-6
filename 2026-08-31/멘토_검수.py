# 문제 5. 한 번 걸러내고 끝내면 안 된다
# ----------------------------------------
# 압력 이상값을 라인별 z-점수 임계값 3으로 찾으세요.
# 먼저 C라인 압력의 표준편차를 출력하고, 걸린 개수와 걸린 행의 라인·압력을 출력합니다.
# 걸린 값을 그 라인의 중앙값으로 바꾼 뒤, C라인 압력의 표준편차를 다시 출력하세요.
# 그리고 같은 방법으로 한 번 더 탐지해 개수와 걸린 행을 출력하세요.
# 2차에서도 걸리면 같은 방법으로 처리하고, 3차에서 0건이 되는지 확인하세요.
# 마지막으로 라인별 행 수를 출력하세요.
#
# [확인 항목]
#   - 1차 처리 전후로 C라인 압력 표준편차가 크게 줄어든다. 얼마에서 얼마로 줄었는가
#   - 2차에서 1차 때는 안 걸리던 값이 새로 걸린다. 왜 1차에서는 안 걸렸는가
#   - 3차에서 0건이 되어야 멈춘다. 한 번만 돌리고 끝냈다면 무엇을 놓쳤겠는가
#   - 행을 지우지 않았으므로 라인별 행 수가 그대로여야 한다
#
# [멘티에게 한 문장으로]
#   "큰 이상값 하나가 표준편차를 부풀려서 작은 이상값을 ..."
print("\n문제 5 -----------------------------------")


def line_zscore(df, col):
    return df.groupby("생산라인")[col].transform(lambda s: (s - s.mean()) / s.std(ddof=0))


print("C라인 압력 표준편차(처리 전):", round(cleaned2.loc[cleaned2["생산라인"] == "C라인", "압력"].std(ddof=0), 4))

cleaned3 = cleaned2.copy()
round_num = 0
while True:
    round_num += 1
    outlier_mask = line_zscore(cleaned3, "압력").abs() > 3
    count = outlier_mask.sum()
    print(f"{round_num}차 검출:", count)
    if count == 0:
        break
    print(cleaned3.loc[outlier_mask, ["검사일시", "생산라인", "압력"]])
    median_vals = cleaned3.groupby("생산라인")["압력"].transform("median")
    cleaned3.loc[outlier_mask, "압력"] = median_vals[outlier_mask]
    if round_num == 1:
        print("C라인 압력 표준편차(1차 처리 후):", round(cleaned3.loc[cleaned3["생산라인"] == "C라인", "압력"].std(ddof=0), 4))

print(cleaned3["생산라인"].value_counts().sort_index())
# [멘티에게] 큰 이상값 하나(13.1, 11.8, 12.5)가 C라인 압력의 표준편차를 1.25까지 부풀려서,
# 그보다 작은 이상값(7.88, 7.95)은 "표준편차 3배" 문턱 안에 숨어 있었다. 1차에서 큰 값을
