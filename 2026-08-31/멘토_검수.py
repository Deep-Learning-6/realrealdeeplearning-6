# 문제 7. 스케일 기준은 학습에서만 잡는다
# ----------------------------------------
# 시드 6으로 행 순서를 섞어 6:2:2 로 학습·검증·테스트를 나누고 각 크기를 출력하세요.
# (경계는 전체 길이의 0.6, 0.8 지점을 정수로 자릅니다)
# 센서 4열에 대해 '학습 데이터만'의 min·max 기준표를 만들고,
# '표 전체'의 min·max 와 나란히 출력하세요. 학습 기준표는 스케일링기준.csv 로 저장합니다.
# 이어서 테스트 데이터를 두 기준으로 각각 변환해 비교하세요.
#   (1) 0~1 밖으로 나간 값의 개수 - 전체 기준 / 학습 기준
#   (2) 정확히 0 또는 1인 칸의 개수 - 전체 기준 / 학습 기준
#   (3) 학습 기준 변환값의 열별 최댓값
#
# [확인 항목]
#   - 전체 기준으로는 0~1 밖 값이 하나도 안 나온다. 좋아 보이지만 이게 누출의 증거다
#   - 전체 기준에서는 테스트 행이 정확히 0이나 1이 되는 칸이 더 많이 나온다.
#     그 행의 값이 곧 기준의 min 또는 max 였다는 뜻이다. 왜 이게 문제인가
#   - 학습 기준에서는 0~1 밖 값이 나온다. 이건 오류가 아니다. 왜 정상인가
#
# [멘티에게 한 문장으로]
#   "테스트 값이 1을 넘은 건 잘못된 게 아니라 ..."
print("\n문제 7 -----------------------------------")
n = len(cleaned3)
rng = np.random.default_rng(6)
order = rng.permutation(n)
cut1, cut2 = int(n * 0.6), int(n * 0.8)
train_idx, val_idx, test_idx = order[:cut1], order[cut1:cut2], order[cut2:]
print(len(train_idx), len(val_idx), len(test_idx))

train_df = cleaned3.iloc[train_idx]
full_range = pd.DataFrame({"min": cleaned3[SENSORS].min(), "max": cleaned3[SENSORS].max()})
train_range = pd.DataFrame({"min": train_df[SENSORS].min(), "max": train_df[SENSORS].max()})
print(full_range)
print(train_range)
train_range.to_csv("스케일링기준.csv", encoding="utf-8-sig")

test_df = cleaned3.iloc[test_idx]


def apply_minmax(df, range_df):
    result = df[SENSORS].copy()
    for col in SENSORS:
        result[col] = (df[col] - range_df.loc[col, "min"]) / (range_df.loc[col, "max"] - range_df.loc[col, "min"])
    return result


test_scaled_full = apply_minmax(test_df, full_range)
test_scaled_train = apply_minmax(test_df, train_range)

print("(1) 0~1 밖 - 전체기준:", ((test_scaled_full < 0) | (test_scaled_full > 1)).sum().sum(),
      "/ 학습기준:", ((test_scaled_train < 0) | (test_scaled_train > 1)).sum().sum())
print("(2) 정확히 0 또는 1 - 전체기준:", ((test_scaled_full == 0) | (test_scaled_full == 1)).sum().sum(),
      "/ 학습기준:", ((test_scaled_train == 0) | (test_scaled_train == 1)).sum().sum())
print("(3) 학습 기준 변환값 열별 최댓값")
print(test_scaled_train.max().round(4))
# [멘티에게] 테스트 값이 1을 넘은 건 잘못된 게 아니라, 학습 데이터가 보지 못한 범위를
# 테스트가 갖고 있다는 정상적인 신호다. s1.py 문제 9에는 애초에 학습/검증/테스트 구분이
# 없었다 - 표 전체를 기준으로 정규화했기 때문에, 지금 우리가 "테스트로 떼어낸" 행들의
# 값도 그때 이미 min·max 계산에 들어가 있었다. 그래서 전체 기준으로 스케일을 잡으면
# 테스트 값이 0~1을 절대 벗어날 수 없고, 심지어 테스트 행이 정확히 0이나 1을 찍는 칸도
# 더 많이 나온다 - 그 행 자체가 기준의 최솟값·최댓값이었다는 뜻이다. 이건 정확도가 아니라
# "미래 정보(테스트)가 기준을 만드는 데 이미 쓰였다"는 데이터 누출의 증거다.


