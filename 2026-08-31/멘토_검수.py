# 문제 6. 같은 행인데 스케일 값이 다르다
# ----------------------------------------
# 멘티가 넘긴 정규화_멘티.csv 와, 문제 5까지 정리한 여러분의 표를 같은 방식으로
# (표 전체 min·max 기준) 정규화한 결과를 나란히 놓고 비교하세요.
# 검사일시와 생산라인을 이어 붙인 값을 키로 두 표를 맞추면 됩니다.
#
# (1) 맞춰진 행 수
# (2) 센서별 두 값의 차이 최댓값
# (3) 센서별 차이가 0.05를 넘는 행의 개수
# (4) 온도 차이가 큰 상위 4개 행의 키·멘티값·멘토값
# (5) 라인별 정규화 온도 평균 - 멘티 / 멘토 두 칸짜리 표
#
# [확인 항목]
#   - 같은 검사 기록인데 스케일 값이 0.4 넘게 벌어진 행이 있다. 어느 행들인가
#   - 손대지 않은 열은 차이가 0이다. 어느 열이고, 그게 무엇을 뜻하는가
#   - 어느 쪽이 옳은지는 (5)로 판정한다. A라인 정상 온도가 정규화되면 0.1 근처여야 하는데
#     0.536이라는 값은 A라인 어디에도 없는 값이다
#
# [멘티에게 한 문장으로]
#   "같은 A라인 기록인데 0.061이 아니라 0.536으로 찍힌 이유는 ..."
print("\n문제 6 -----------------------------------")
mentor_norm = cleaned3.copy()
for col in SENSORS:
    mentor_norm[col] = (cleaned3[col] - cleaned3[col].min()) / (cleaned3[col].max() - cleaned3[col].min())

mentor_norm["키"] = mentor_norm["검사일시"] + "_" + mentor_norm["생산라인"]
mentee_norm = mentee_norm.copy()
mentee_norm["키"] = mentee_norm["검사일시"] + "_" + mentee_norm["생산라인"]
merged = pd.merge(mentee_norm, mentor_norm, on="키", suffixes=("_멘티", "_멘토"))
print("(1) 맞춰진 행 수:", len(merged))

print("(2)(3) 센서별 최대 차이 / 0.05 초과 행 수")
for col in SENSORS:
    diff = (merged[f"{col}_멘티"] - merged[f"{col}_멘토"]).abs()
    print(col, round(diff.max(), 4), (diff > 0.05).sum())

merged["온도차이"] = (merged["온도_멘티"] - merged["온도_멘토"]).abs()
print("(4) 온도 차이 상위 4행")
print(merged.sort_values("온도차이", ascending=False).head(4)[["키", "온도_멘티", "온도_멘토", "온도차이"]])

merged["생산라인"] = merged["생산라인_멘토"]
print("(5) 라인별 정규화 온도 평균")
print(merged.groupby("생산라인")[["온도_멘티", "온도_멘토"]].mean().round(4))
# [멘티에게] 같은 A라인 기록인데 0.061이 아니라 0.536으로 찍힌 이유는, s1.py 문제 9가
# "표 전체의 최솟값·최댓값"으로 정규화하라고 지시한 시점에 문제 7~8에서 못 걸러낸 압력
# 이상값과, 문제 4의 전체 평균 채우기로 오염된 온도값이 아직 표에 남아 있었기 때문이다.
# 그 이상값이 압력 열의 max를 밀어 올려서 다른 모든 압력값의 분모가 커졌고, 압력만이
# 아니라 그 행이 속한 조합 전체의 스케일 감각이 흔들렸다. 손대지 않은 회전수는 두 결과의
# 차이가 0에 가까운데, 이는 그 열만큼은 이상값·결측 처리의 영향을 안 받았다는 뜻이고,
# 반대로 온도·압력·진동의 차이가 큰 것은 딱 우리가 고친 부분과 정확히 겹친다는 뜻이다.


